import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { build } from 'esbuild';
const result=await build({entryPoints:['src.js'],bundle:true,format:'iife',minify:true,write:false,target:'es2022'});
let html=await readFile('index.html','utf8');
const css=await readFile('style.css','utf8');
const script=result.outputFiles[0].text.replace(/<\/script/gi,'<\\/script');
const hash=createHash('sha256').update(script).digest('base64');
html=html.replace("script-src 'self';",`script-src 'self' 'sha256-${hash}';`);
html=html.replace('<link rel="stylesheet" href="./style.css">',()=>`<style>${css}</style>`).replace('<script type="module" src="./src.js"></script>',()=>`<script>${script}</script>`);
await writeFile('vale-do-sol.html',html);
console.log('Versão offline atualizada: vale-do-sol.html');
